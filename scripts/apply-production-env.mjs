#!/usr/bin/env node
/**
 * Apply go-live production env to the linked Vercel project (non-interactive).
 *
 * Usage:
 *   node scripts/apply-production-env.mjs              # flags + generated secrets
 *   node scripts/apply-production-env.mjs --flags-only  # no API/session secrets
 *   node scripts/apply-production-env.mjs --dry-run
 *
 * Does not set Stripe live keys (provide via STRIPE_* env or vercel dashboard).
 * Does not set DATABASE_URL (provision Neon first, then re-run with DATABASE_URL set).
 */
import { randomBytes } from "node:crypto";
import { spawnSync } from "node:child_process";

const DRY = process.argv.includes("--dry-run");
const FLAGS_ONLY = process.argv.includes("--flags-only");
const SCOPE = process.env.VERCEL_SCOPE || "hondo4185-5820s-projects";

/** @type {{ key: string, value: string, sensitive?: boolean }[]} */
const FLAGS = [
  { key: "APP_BASE_URL", value: "https://siskelbot.vercel.app" },
  { key: "ENFORCE_PLAN_LIMITS", value: "1" },
  { key: "QUOTA_ENABLED", value: "1" },
  { key: "HEALTH_DEEP_BACKEND_OPTIONAL", value: "1" },
  { key: "OTEL_ENABLED", value: "1" },
];

function vercelEnvAdd(key, value, { sensitive = false } = {}) {
  if (DRY) {
    console.log(`[dry-run] ${key}=${sensitive ? "<redacted>" : value}`);
    return true;
  }
  const args = ["vercel", "env", "add", key, "production", "--yes", "--force", "--scope", SCOPE];
  if (sensitive) args.push("--sensitive");
  const r = spawnSync("npx", args, {
    input: String(value),
    encoding: "utf8",
    shell: process.platform === "win32",
    stdio: ["pipe", "pipe", "pipe"],
  });
  const out = `${r.stdout || ""}${r.stderr || ""}`;
  if (r.status !== 0) {
    console.error(`Failed ${key}:`, out.trim() || `exit ${r.status}`);
    return false;
  }
  console.log(`Set ${key}`);
  return true;
}

async function main() {
  let ok = true;
  for (const f of FLAGS) {
    if (!vercelEnvAdd(f.key, f.value)) ok = false;
  }

  const databaseUrl = process.env.DATABASE_URL?.trim();
  if (databaseUrl) {
    if (!vercelEnvAdd("STORAGE_BACKEND", "postgres")) ok = false;
    if (!vercelEnvAdd("DATABASE_URL", databaseUrl, { sensitive: true })) ok = false;
    if (!vercelEnvAdd("REQUIRE_DURABLE_STORAGE", "1")) ok = false;
  } else {
    console.log("Skip STORAGE_BACKEND/DATABASE_URL/REQUIRE_DURABLE_STORAGE (set DATABASE_URL and re-run)");
  }

  const stripeSecret = process.env.STRIPE_SECRET_KEY?.trim();
  const stripeWebhook = process.env.STRIPE_WEBHOOK_SECRET?.trim();
  const stripePro = process.env.STRIPE_PRO_PRICE_ID?.trim();
  const stripeEnt = process.env.STRIPE_ENTERPRISE_PRICE_ID?.trim();
  if (stripeSecret) {
    if (!vercelEnvAdd("STRIPE_SECRET_KEY", stripeSecret, { sensitive: true })) ok = false;
  } else {
    console.log("Skip STRIPE_SECRET_KEY (export and re-run, or set in Vercel dashboard)");
  }
  if (stripeWebhook) {
    if (!vercelEnvAdd("STRIPE_WEBHOOK_SECRET", stripeWebhook, { sensitive: true })) ok = false;
  }
  if (stripePro) {
    if (!vercelEnvAdd("STRIPE_PRO_PRICE_ID", stripePro)) ok = false;
  }
  if (stripeEnt) {
    if (!vercelEnvAdd("STRIPE_ENTERPRISE_PRICE_ID", stripeEnt)) ok = false;
  }

  if (!FLAGS_ONLY) {
    const apiKey = process.env.API_KEY?.trim() || `sb_live_${randomBytes(24).toString("hex")}`;
    const adminKey = process.env.ADMIN_API_KEY?.trim() || `sb_admin_${randomBytes(24).toString("hex")}`;
    const sessionSecret = process.env.SESSION_SECRET?.trim() || randomBytes(32).toString("hex");
    if (!vercelEnvAdd("API_KEY", apiKey, { sensitive: true })) ok = false;
    if (!vercelEnvAdd("ADMIN_API_KEY", adminKey, { sensitive: true })) ok = false;
    if (!vercelEnvAdd("SESSION_SECRET", sessionSecret, { sensitive: true })) ok = false;
    if (!DRY) {
      const { writeFileSync } = await import("node:fs");
      writeFileSync(
        ".env.production.secrets.local",
        [
          "# Generated by apply-production-env.mjs — DO NOT COMMIT",
          `API_KEY=${apiKey}`,
          `ADMIN_API_KEY=${adminKey}`,
          `SESSION_SECRET=${sessionSecret}`,
          "",
        ].join("\n"),
        { mode: 0o600 }
      );
      console.log("Wrote .env.production.secrets.local (gitignored) for GH secret sync");
    }
  }

  if (!ok) process.exit(1);
  console.log("\nDone. Redeploy: npx vercel --prod --yes --scope", SCOPE);
}

main();
