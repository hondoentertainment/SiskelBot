/**
 * Phase 61.4: Local dev environment.
 *
 * One-command dev setup: writes a sensible .env.local, seeds the data/
 * directory with a chosen template (minimal | demo | testing | full), and
 * exposes helpers for verifying the host environment.
 *
 * No external dependencies — everything uses Node's built-in fs/promises,
 * path, crypto, and net modules. JSON files match the shape expected by
 * lib/json-path-store.js and lib/storage.js so the rest of SiskelBot can
 * pick them up as soon as the server boots.
 *
 * @module dev-setup
 */

