// ─── Helpers ────────────────────────────────────────────────────────────────

function sha256(s) {
  return crypto.createHash("sha256").update(String(s)).digest("hex");
}

function randomHex(bytes = 24) {
  return crypto.randomBytes(bytes).toString("hex");
}

function makeId(prefix = "id") {
  return `${prefix}_${Date.now().toString(36)}_${crypto.randomBytes(4).toString("hex")}`;
}

async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function ensureDir(p) {
  await fs.mkdir(p, { recursive: true });
}

async function writeJson(filePath, data) {
  await ensureDir(path.dirname(filePath));
  await fs.writeFile(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
}

async function readJsonSafe(filePath, fallback) {
  try {
    const txt = await fs.readFile(filePath, "utf8");
    return JSON.parse(txt);
  } catch {
    return fallback;
  }
}

function storagePathRoot(storagePath) {
  return path.resolve(storagePath || process.env.STORAGE_PATH || "./data");
}

function userScopePath(root, userId, workspaceId) {
  return path.join(root, "users", userId, "workspaces", workspaceId);
}

// ─── Env file generation ───────────────────────────────────────────────────

const ENV_DEFAULTS = [
  { key: "NODE_ENV", value: "development", comment: "Mode" },
  { key: "PORT", value: "3000", comment: "HTTP port" },
  { key: "BACKEND", value: "ollama", comment: "ollama | vllm | openai" },
  { key: "OLLAMA_URL", value: "http://localhost:11434", comment: "Ollama" },
  { key: "VLLM_URL", value: "http://localhost:8000", comment: "vLLM" },
  { key: "STORAGE_BACKEND", value: "json", comment: "json | sqlite | postgres" },
  { key: "STORAGE_PATH", value: "./data", comment: "JSON storage root" },
  { key: "SESSION_SECRET", value: "dev-secret-change-me", comment: "Session cookie secret" },
  { key: "API_KEY", value: "", comment: "Protects /v1/chat/completions (optional in dev)" },
  { key: "ADMIN_API_KEY", value: "", comment: "Protects /admin and /api/admin/*" },
  { key: "OPENAI_API_KEY", value: "", comment: "Set when BACKEND=openai" },
  { key: "ENABLE_METRICS", value: "1", comment: "Expose /metrics" },
];

export async function generateEnvFile(options = {}) {
  const targetPath = options.envPath ? path.resolve(options.envPath) : path.resolve(process.cwd(), ".env.local");
  const force = Boolean(options.force);
  const overrides = options.overrides && typeof options.overrides === "object" ? options.overrides : {};

  if (!force && (await exists(targetPath))) {
    return { path: targetPath, written: false, reason: "exists" };
  }

  const entries = ENV_DEFAULTS.map((entry) => {
    const v = Object.prototype.hasOwnProperty.call(overrides, entry.key) ? overrides[entry.key] : entry.value;
    return { ...entry, value: v };
  });

  // Auto-generate a session secret and admin key if none supplied
  const sessionEntry = entries.find((e) => e.key === "SESSION_SECRET");
  if (sessionEntry && (!sessionEntry.value || sessionEntry.value === "dev-secret-change-me")) {
    sessionEntry.value = "dev_" + randomHex(16);
  }
  const adminEntry = entries.find((e) => e.key === "ADMIN_API_KEY");
  if (adminEntry && !adminEntry.value) {
    adminEntry.value = "dev_admin_" + randomHex(12);
  }

  const header = [
    "# SiskelBot local dev environment",
    "# Generated by lib/dev-setup.js — safe to edit, regenerate with --force.",
    "# DO NOT commit this file; it may contain secrets.",
    "",
  ];
  const body = entries.map((e) => {
    const commentLine = e.comment ? `# ${e.comment}` : "";
    return `${commentLine}\n${e.key}=${e.value ?? ""}`.trim();
  });

  const content = header.concat(body).join("\n") + "\n";
  await ensureDir(path.dirname(targetPath));
  await fs.writeFile(targetPath, content, "utf8");
  return { path: targetPath, written: true };
}

// ─── User / workspace / API key primitives ─────────────────────────────────

export async function createTestUser({ email, role = "user", apiKey, storagePath } = {}) {
  const root = storagePathRoot(storagePath);
  const userId = makeId("user");
  const user = {
    id: userId,
    email: email || `dev-${userId}@example.com`,
    role,
    createdAt: new Date().toISOString(),
    _seed: true,
  };
  const usersPath = path.join(root, "users.json");
  const data = await readJsonSafe(usersPath, { users: [], _version: 1 });
  const arr = Array.isArray(data.users) ? data.users : [];
  // Idempotency: skip if an identical seeded email already exists
  const existing = arr.find((u) => u.email === user.email && u._seed);
  if (existing) return existing;
  arr.push(user);
  await writeJson(usersPath, { users: arr, _version: 1 });

  // Also create the user's personal workspace directory so storage.js list() works
  await ensureDir(userScopePath(root, userId, "default"));

  if (apiKey) {
    await createTestApiKey({ userId, rawKey: apiKey, storagePath: root });
  }
  return user;
}

export async function createTestWorkspace({ name, ownerId, type = "personal", storagePath } = {}) {
  const root = storagePathRoot(storagePath);
  if (!ownerId) throw new Error("ownerId required");
  const workspaceId = makeId("ws");
  const workspace = {
    id: workspaceId,
    name: name || "Dev Workspace",
    ownerId,
    type,
    createdAt: new Date().toISOString(),
    _seed: true,
  };
  const wsDir = path.join(root, "users", ownerId, "workspaces");
  await ensureDir(path.join(wsDir, workspaceId));
  const indexPath = path.join(wsDir, "index.json");
  const data = await readJsonSafe(indexPath, { workspaces: [], _version: 1 });
  const list = Array.isArray(data.workspaces) ? data.workspaces : [];
  const dup = list.find((w) => w.name === workspace.name && w._seed);
  if (dup) return dup;
  list.push(workspace);
  await writeJson(indexPath, { workspaces: list, _version: 1 });
  return workspace;
}

export async function createTestApiKey({ userId, scopes = ["read", "write"], rawKey, storagePath } = {}) {
  const root = storagePathRoot(storagePath);
  if (!userId) throw new Error("userId required");
  const key = rawKey || "sk-dev-" + randomHex(18);
  const entry = {
    id: makeId("key"),
    keyHash: sha256(key),
    masked: key.slice(0, 6) + "…" + key.slice(-4),
    userId,
    scopes: Array.isArray(scopes) && scopes.length ? scopes : ["read", "write"],
    createdAt: new Date().toISOString(),
    _seed: true,
  };
  const filePath = path.join(root, "api-keys.json");
  const data = await readJsonSafe(filePath, { keys: [], _version: 1 });
  const keys = Array.isArray(data.keys) ? data.keys : [];
  keys.push(entry);
  await writeJson(filePath, { keys, _version: 1 });
  return { ...entry, key };
}

// ─── Seeders ────────────────────────────────────────────────────────────────

export async function seedMinimal(storagePath) {
  const root = storagePathRoot(storagePath);
  await ensureDir(root);
  // Ensure the default workspace folder exists so storage reads don't crash.
  await ensureDir(userScopePath(root, "anonymous", "default"));
  // Stamp a marker file so getDevStatus can detect a seed has run.
  const markerPath = path.join(root, ".dev-seed.json");
  await writeJson(markerPath, {
    template: "minimal",
    seededAt: new Date().toISOString(),
    _version: 1,
  });
  return { template: "minimal", root };
}

export async function seedDemo(storagePath) {
  const root = storagePathRoot(storagePath);
  await seedMinimal(root);
  const user = await createTestUser({
    email: "demo@example.com",
    role: "user",
    storagePath: root,
  });
  const workspace = await createTestWorkspace({
    name: "Demo Workspace",
    ownerId: user.id,
    storagePath: root,
  });
  // Seed a couple of sample conversations under the demo workspace
  const convPath = path.join(userScopePath(root, user.id, workspace.id), "conversations.json");
  const conversations = [
    {
      id: makeId("conv"),
      title: "Welcome to SiskelBot",
      messages: [
        { role: "user", content: "Hello!" },
        { role: "assistant", content: "Hi there — this is a demo conversation." },
      ],
      createdAt: new Date().toISOString(),
      _seed: true,
    },
    {
      id: makeId("conv"),
      title: "Sample agent run",
      messages: [
        { role: "user", content: "Plan a trip to Chicago." },
        { role: "assistant", content: "Here's an example plan…" },
      ],
      createdAt: new Date().toISOString(),
      _seed: true,
    },
  ];
  await writeJson(convPath, { items: conversations, _version: 1 });
  await writeJson(path.join(root, ".dev-seed.json"), {
    template: "demo",
    seededAt: new Date().toISOString(),
    users: 1,
    workspaces: 1,
    _version: 1,
  });
  return { template: "demo", root, user, workspace };
}

export async function seedTesting(storagePath) {
  const root = storagePathRoot(storagePath);
  await seedMinimal(root);
  const users = [];
  const keys = [];
  const workspaces = [];
  const roles = ["admin", "user", "viewer"];
  for (let i = 0; i < 3; i++) {
    const user = await createTestUser({
      email: `test-${i + 1}@example.com`,
      role: roles[i],
      storagePath: root,
    });
    users.push(user);
    const ws = await createTestWorkspace({
      name: `Test WS ${i + 1}`,
      ownerId: user.id,
      storagePath: root,
    });
    workspaces.push(ws);
    const key = await createTestApiKey({
      userId: user.id,
      scopes: roles[i] === "admin" ? ["read", "write", "admin"] : ["read", "write"],
      rawKey: `sk-test-${i + 1}-` + randomHex(8),
      storagePath: root,
    });
    keys.push(key);
  }
  // Preset conversations for the admin test user
  const admin = users[0];
  const adminWs = workspaces[0];
  const convPath = path.join(userScopePath(root, admin.id, adminWs.id), "conversations.json");
  const conversations = Array.from({ length: 4 }).map((_, i) => ({
    id: makeId("conv"),
    title: `Preset conversation ${i + 1}`,
    messages: [
      { role: "user", content: `Test message ${i + 1}` },
      { role: "assistant", content: `Test reply ${i + 1}` },
    ],
    createdAt: new Date().toISOString(),
    _seed: true,
  }));
  await writeJson(convPath, { items: conversations, _version: 1 });

  await writeJson(path.join(root, ".dev-seed.json"), {
    template: "testing",
    seededAt: new Date().toISOString(),
    users: users.length,
    workspaces: workspaces.length,
    apiKeys: keys.length,
    _version: 1,
  });
  return { template: "testing", root, users, workspaces, apiKeys: keys };
}

