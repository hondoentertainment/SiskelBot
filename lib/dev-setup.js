// ─── Verification / health ─────────────────────────────────────────────────

export async function checkDependencies() {
  const checks = [];
  // Node version
  const nodeVersion = process.versions.node;
  const major = Number(nodeVersion.split(".")[0] || 0);
  checks.push({
    name: "node_version",
    ok: major >= 18,
    detail: nodeVersion,
    required: ">=18",
  });
  // package.json presence
  const pkgPath = path.resolve(process.cwd(), "package.json");
  checks.push({
    name: "package_json",
    ok: await exists(pkgPath),
    detail: pkgPath,
  });
  // node_modules presence (soft check)
  const nmPath = path.resolve(process.cwd(), "node_modules");
  checks.push({
    name: "node_modules",
    ok: await exists(nmPath),
    detail: nmPath,
  });
  return { ok: checks.every((c) => c.ok), checks };
}

export async function checkPortAvailable(port) {
  const p = Number(port || DEFAULT_PORT);
  return await new Promise((resolve) => {
    const server = net.createServer();
    server.once("error", () => resolve({ port: p, available: false }));
    server.once("listening", () => {
      server.close(() => resolve({ port: p, available: true }));
    });
    try {
      server.listen({ port: p, host: "127.0.0.1", exclusive: true });
    } catch {
      resolve({ port: p, available: false });
    }
  });
}

export async function verifyEnvironment(options = {}) {
  const checks = [];
  const deps = await checkDependencies();
  checks.push(...deps.checks);

  // Data directory writable
  const root = storagePathRoot(options.storagePath);
  let dataOk = false;
  let dataDetail = root;
  try {
    await ensureDir(root);
    const probe = path.join(root, ".dev-write-probe");
    await fs.writeFile(probe, "ok", "utf8");
    await fs.unlink(probe);
    dataOk = true;
  } catch (err) {
    dataDetail = `${root}: ${err.message}`;
  }
  checks.push({ name: "data_writable", ok: dataOk, detail: dataDetail });

  // Port check (soft, informational)
  const port = Number(options.port || process.env.PORT || DEFAULT_PORT);
  const portStatus = await checkPortAvailable(port);
  checks.push({
    name: "port_available",
    ok: portStatus.available,
    detail: String(port),
  });

  // Required env vars (only when BACKEND=openai do we require OPENAI_API_KEY)
  const backend = process.env.BACKEND || "ollama";
  const envRequired = [];
  if (backend === "openai") envRequired.push("OPENAI_API_KEY");
  for (const key of envRequired) {
    checks.push({
      name: `env_${key}`,
      ok: Boolean(process.env[key]),
      detail: process.env[key] ? "set" : "missing",
    });
  }

  return { ok: checks.every((c) => c.ok), checks };
}

// ─── Orchestrator ──────────────────────────────────────────────────────────

export async function runSetup(options = {}) {
  const seed = options.seed || "minimal";
  if (!SEED_TEMPLATES[seed]) {
    throw new Error(`Unknown seed template: ${seed}. Valid: ${Object.keys(SEED_TEMPLATES).join(", ")}`);
  }
  const writeEnv = options.writeEnv !== false;
  const force = Boolean(options.force);
  const storagePath = storagePathRoot(options.storagePath);

  const createdFiles = [];
  const warnings = [];

  // 1. Env file
  let envResult = null;
  if (writeEnv) {
    envResult = await generateEnvFile({
      envPath: options.envPath,
      force,
    });
    if (envResult.written) createdFiles.push(envResult.path);
    else if (envResult.reason === "exists") warnings.push(`.env.local already exists; use force=true to overwrite.`);
  }

  // 2. Data seeding
  await ensureDir(storagePath);
  let seedResult;
  switch (seed) {
    case "demo":
      seedResult = await seedDemo(storagePath);
      break;
    case "testing":
      seedResult = await seedTesting(storagePath);
      break;
    case "full":
      seedResult = await seedFull(storagePath);
      break;
    case "minimal":
    default:
      seedResult = await seedMinimal(storagePath);
      break;
  }
  createdFiles.push(path.join(storagePath, ".dev-seed.json"));

  // 3. Next steps summary
  const nextSteps = [
    "Review .env.local and set any empty values you need (e.g. OPENAI_API_KEY).",
    "Start the server with `npm run dev`.",
    "Open http://localhost:3000 to access the UI.",
  ];

  return {
    success: true,
    seed,
    storagePath,
    createdFiles,
    warnings,
    env: envResult,
    data: seedResult,
    nextSteps,
  };
}

// ─── Reset / status ────────────────────────────────────────────────────────

export async function resetDevEnvironment(options = {}) {
  if (!options.confirm) {
    return { ok: false, error: "Reset requires { confirm: true }." };
  }
  const removed = [];
  const storagePath = storagePathRoot(options.storagePath);
  const envPath = options.envPath ? path.resolve(options.envPath) : path.resolve(process.cwd(), ".env.local");

  if (await exists(storagePath)) {
    try {
      await fs.rm(storagePath, { recursive: true, force: true });
      removed.push(storagePath);
    } catch (err) {
      return { ok: false, error: `Failed to remove ${storagePath}: ${err.message}` };
    }
  }
  if (await exists(envPath)) {
    try {
      await fs.unlink(envPath);
      removed.push(envPath);
    } catch (err) {
      return { ok: false, error: `Failed to remove ${envPath}: ${err.message}` };
    }
  }
  return { ok: true, removed };
}

export async function getDevStatus(options = {}) {
  const storagePath = storagePathRoot(options.storagePath);
  const envPath = options.envPath ? path.resolve(options.envPath) : path.resolve(process.cwd(), ".env.local");

  const envExists = await exists(envPath);
  const storageExists = await exists(storagePath);
  const markerPath = path.join(storagePath, ".dev-seed.json");
  const marker = (await exists(markerPath)) ? await readJsonSafe(markerPath, null) : null;

  // Count users/workspaces/apiKeys from seed files if present
  const usersData = await readJsonSafe(path.join(storagePath, "users.json"), { users: [] });
  const keysData = await readJsonSafe(path.join(storagePath, "api-keys.json"), { keys: [] });

  return {
    envFile: { path: envPath, exists: envExists },
    storage: {
      path: storagePath,
      exists: storageExists,
      seed: marker?.template || null,
      seededAt: marker?.seededAt || null,
    },
    counts: {
      users: Array.isArray(usersData.users) ? usersData.users.length : 0,
      apiKeys: Array.isArray(keysData.keys) ? keysData.keys.length : 0,
    },
    node: process.versions.node,
  };
}

